# =============================================================================
# Hybrid CNN + KAN model
#
# Standard convs downsample the long time axis cheaply; KAN layers operate on
# the shorter, richer sequences where their cost is affordable. tanh squashes
# activations into the KAN grid_range so the spline branch stays active.
# =============================================================================
def build_seizure_model_hybrid(input_shape, learning_rate=1e-4, threshold=0.50,
                               dropout_factor=0.25, grid_size=KAN_GRID_SIZE,
                               spline_order=KAN_SPLINE_ORDER):
    inputs = layers.Input(shape=input_shape, name='eeg_input')
    kan_kwargs = dict(grid_size=grid_size, spline_order=spline_order)

    # --- Standard conv front-end: cheap downsampling of the long axis ---
    x = Conv1D(32, 7, strides=2, padding='same', activation='relu')(inputs)
    x = layers.BatchNormalization()(x)
    x = layers.MaxPooling1D(2)(x)
    x = layers.Dropout(0.2 * dropout_factor)(x)

    x = Conv1D(64, 5, padding='same', activation='relu')(x)
    x = layers.BatchNormalization()(x)
    x = layers.MaxPooling1D(2)(x)
    x = layers.Dropout(0.2 * dropout_factor)(x)

    # --- KAN back-end: learnable activations on short sequences ---
    x = layers.Activation('tanh')(x)                       # squash into grid_range
    x = KANConv1D(128, kernel_size=3, padding='SAME',
                  dtype='float32', **kan_kwargs)(x)         # keep KAN in fp32
    x = layers.BatchNormalization()(x)
    x = layers.MaxPooling1D(2)(x)
    x = layers.Dropout(0.3 * dropout_factor)(x)

    x = layers.Activation('tanh')(x)
    x = KANConv1D(256, kernel_size=3, padding='SAME',
                  dtype='float32', **kan_kwargs)(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(0.3 * dropout_factor)(x)

    x = layers.GlobalAveragePooling1D()(x)

    x = layers.Activation('tanh')(x)
    x = KANLinear(64, dtype='float32', **kan_kwargs)(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(0.5 * dropout_factor)(x)

    x = layers.Activation('tanh')(x)
    logits = KANLinear(1, dtype='float32', **kan_kwargs)(x)
    outputs = layers.Activation('sigmoid', dtype='float32',
                                name='seizure_output')(logits)

    model = Model(inputs=inputs, outputs=outputs,
                  name='SeizureDetector_HybridKAN')

    model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=learning_rate),
        loss='binary_crossentropy',
        metrics=[
            tf.keras.metrics.BinaryAccuracy(name='accuracy', threshold=threshold),
            BalancedAccuracy(name='balanced_accuracy', threshold=threshold),
            tf.keras.metrics.AUC(name='auc'),
            tf.keras.metrics.Precision(name='precision', thresholds=threshold),
            tf.keras.metrics.Recall(name='recall', thresholds=threshold),
        ],
    )
    return model


