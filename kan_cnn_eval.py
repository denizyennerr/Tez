# =============================================================================
# Streaming .npz -> .npy memmap conversion
#
# Never holds the full array in RAM: decompresses one chunk of rows at a time.
# Peak RAM during conversion is ~ chunk * sample_size (a few MB).
# =============================================================================
def _stream_member(npz_path, member, out_path, dtype=np.float32, chunk=512):
    """Decompress a single .npz member into a .npy memmap, chunk by chunk."""
    with zipfile.ZipFile(npz_path) as zf, zf.open(member + '.npy') as f:
        version = npformat.read_magic(f)
        try:
            shape, fortran, src_dtype = npformat._read_array_header(f, version)
        except AttributeError:
            # Older NumPy private API fallback (assumes v1.0 header).
            shape, fortran, src_dtype = npformat.read_array_header_1_0(f)

        if fortran:
            raise ValueError(
                f"'{member}' is Fortran-ordered; re-save it C-contiguous first."
            )

        out = npformat.open_memmap(out_path, mode='w+', dtype=dtype, shape=shape)
        row_bytes = int(np.prod(shape[1:])) * src_dtype.itemsize
        for start in range(0, shape[0], chunk):
            n = min(chunk, shape[0] - start)
            buf = f.read(row_bytes * n)
            arr = np.frombuffer(buf, dtype=src_dtype).reshape((n,) + shape[1:])
            out[start:start + n] = arr.astype(dtype, copy=False)
        out.flush()
        del out
        gc.collect()
    return shape


def npz_to_memmap(npz_path, drive_cache=DRIVE_CACHE, local_cache=LOCAL_CACHE):
    """
    Return (X_memmap, y, groups).

    X is a read-only memmap on LOCAL disk (never on Drive — random-access reads
    off the Drive FUSE mount are slow and buffer heavily in RAM). Converted
    arrays are also copied to Drive so the conversion is paid only once.
    """
    os.makedirs(drive_cache, exist_ok=True)
    os.makedirs(local_cache, exist_ok=True)
    stem = os.path.splitext(os.path.basename(npz_path))[0]

    paths = {}
    # key -> (npz member name, target dtype or None to copy as-is)
    plan = (('X', 'X', np.float32),
            ('y', 'y', np.float32),
            ('g', 's', None))

    for key, member, dt in plan:
        dpath = os.path.join(drive_cache, f'{stem}_{key}.npy')
        lpath = os.path.join(local_cache, f'{stem}_{key}.npy')

        if not os.path.exists(dpath):
            tmp = lpath + '.tmp'
            if dt is None:
                with np.load(npz_path) as d:      # 'groups' is 1-D and tiny
                    np.save(tmp, d[member])
            else:
                _stream_member(npz_path, member, tmp, dtype=dt)
            os.replace(tmp, lpath)
            shutil.copyfile(lpath, dpath)         # persist for future runtimes
        elif not os.path.exists(lpath):
            shutil.copyfile(dpath, lpath)         # sequential bulk copy is fast

        paths[key] = lpath

    X = np.load(paths['X'], mmap_mode='r')
    y = np.load(paths['y'])
    groups = np.load(paths['g'])

    # Ensure the sample axis is axis 0.
    if X.shape[0] != len(y):
        raise ValueError(
            f"Sample axis mismatch for {stem}: X.shape={X.shape}, len(y)={len(y)}. "
            "Re-save the .npz with samples on axis 0."
        )
    return X, y, groups


